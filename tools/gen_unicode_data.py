#!/usr/bin/env python3
"""Translate Hermes's lib/Platform/Unicode/UnicodeData.inc into Rust.

usage: gen_unicode_data.py <UnicodeData.inc> <out.rs>

The regex compiler must case-fold, classify identifiers and expand \\p{...}
exactly as hermesc does, so it uses Hermes's own tables rather than another
Unicode database. Take the .inc from the Hermes release whose bytecode you
target (HBC 96: the rn/0.73-stable .. rn/0.76-stable branches).
"""

from pathlib import Path
import re
import sys

NUMBER = re.compile(r"-?0x[0-9A-Fa-f]+|-?\d+")

# name in the .inc -> (Rust name, Rust element type, numbers per element)
TABLES = {
    "UNICODE_LETTERS": ("UNICODE_LETTERS", "(u32, u32)", 2),
    "UNICODE_COMBINING_MARK": ("UNICODE_COMBINING_MARK", "(u32, u32)", 2),
    "UNICODE_DIGIT": ("UNICODE_DIGIT", "(u32, u32)", 2),
    "UNICODE_CONNECTOR_PUNCTUATION": ("UNICODE_CONNECTOR_PUNCTUATION", "(u32, u32)", 2),
    "UNICODE_RANGE_POOL": ("RANGE_POOL", "(u32, u32)", 2),
    "UNICODE_RANGE_ARRAY_POOL": ("RANGE_ARRAY_POOL", "(u16, u16)", 2),
    "canonicalPropertyNameMap_GeneralCategory": ("NAMES_GENERAL_CATEGORY", "(u16, u16, u16, u16)", 4),
    "canonicalPropertyNameMap_BinaryProperty": ("NAMES_BINARY_PROPERTY", "(u16, u16, u16, u16)", 4),
    "canonicalPropertyNameMap_Script": ("NAMES_SCRIPT", "(u16, u16, u16, u16)", 4),
    "unicodePropertyRangeMap_GeneralCategory": ("RANGES_GENERAL_CATEGORY", "(u16, u16, u16, u16)", 4),
    "unicodePropertyRangeMap_BinaryProperty": ("RANGES_BINARY_PROPERTY", "(u16, u16, u16, u16)", 4),
    "unicodePropertyRangeMap_Script": ("RANGES_SCRIPT", "(u16, u16, u16, u16)", 4),
    "unicodePropertyRangeMap_ScriptExtensions": ("RANGES_SCRIPT_EXTENSIONS", "(u16, u16, u16, u16)", 4),
    "UNICODE_FOLDS": ("UNICODE_FOLDS", "(u32, u8, i32, u8)", 4),
    "LEGACY_CANONS": ("LEGACY_CANONS", "(u32, u8, i32, u8)", 4),
}

DOCS = {
    "UNICODE_LETTERS": "Lu Ll Lt Lm Lo Nl, as inclusive ranges.",
    "UNICODE_COMBINING_MARK": "Mn Mc, as inclusive ranges.",
    "UNICODE_DIGIT": "Nd, as inclusive ranges.",
    "UNICODE_CONNECTOR_PUNCTUATION": "Pc, as inclusive ranges.",
    "RANGE_POOL": "Inclusive ranges referenced by `RANGE_ARRAY_POOL`.",
    "RANGE_ARRAY_POOL": "(offset, length) slices of `RANGE_POOL`; a property is a list of these.",
    "NAMES_GENERAL_CATEGORY": "(name, canonical name) pairs as (offset, length) into `STRING_POOL`, sorted by name.",
    "NAMES_BINARY_PROPERTY": "As `NAMES_GENERAL_CATEGORY`, for binary properties.",
    "NAMES_SCRIPT": "As `NAMES_GENERAL_CATEGORY`, for Script and Script_Extensions values.",
    "RANGES_GENERAL_CATEGORY": "(canonical name offset, length, `RANGE_ARRAY_POOL` offset, count), sorted by name.",
    "RANGES_BINARY_PROPERTY": "As `RANGES_GENERAL_CATEGORY`, for binary properties.",
    "RANGES_SCRIPT": "As `RANGES_GENERAL_CATEGORY`, for Script.",
    "RANGES_SCRIPT_EXTENSIONS": "As `RANGES_GENERAL_CATEGORY`, for Script_Extensions.",
    "UNICODE_FOLDS": "Simple case folding (`u` flag): (start, count, delta, modulo).",
    "LEGACY_CANONS": "ES Canonicalize without `u` (upper-casing): (start, count, delta, modulo).",
}


def strip_comments(text):
    return re.sub(r"//[^\n]*", "", text)


def main():
    source = Path(sys.argv[1]).read_text()
    out = [
        "// @generated by tools/gen_unicode_data.py from Hermes's",
        "// lib/Platform/Unicode/UnicodeData.inc. Do not edit by hand.",
    ]
    out += [line for line in source.splitlines()[1:17] if line.startswith("// ")]
    out.append("")

    pool = re.search(r"UNICODE_DATA_STRING_POOL\s*=\s*((?:\s*\"[^\"]*\")+)\s*;", source)
    literal = "".join(re.findall(r"\"([^\"]*)\"", pool.group(1)))
    assert "\\" not in literal, "string pool escapes are not handled"
    out.append("/// Names referenced by the property tables.")
    out.append(f"pub(crate) static STRING_POOL: &str = \"{literal}\";")
    out.append("")

    seen = set()
    for match in re.finditer(r"static constexpr \w+ (\w+)\[\]\s*=?\s*\{", source):
        name = match.group(1)
        rust_name, element, width = TABLES[name]
        seen.add(name)
        end = source.index("};", match.end())
        numbers = [int(token, 0) for token in NUMBER.findall(strip_comments(source[match.end():end]))]
        assert len(numbers) % width == 0, name
        rows = [numbers[i:i + width] for i in range(0, len(numbers), width)]
        per_line = 6 if width == 2 else 3
        out.append(f"/// {DOCS[rust_name]}")
        out.append("#[rustfmt::skip]")
        out.append(f"pub(crate) static {rust_name}: &[{element}] = &[")
        for i in range(0, len(rows), per_line):
            cells = []
            for row in rows[i:i + per_line]:
                if width == 2 and element.startswith("(u32"):
                    cells.append(f"(0x{row[0]:X}, 0x{row[1]:X})")
                elif rust_name in ("UNICODE_FOLDS", "LEGACY_CANONS"):
                    cells.append(f"(0x{row[0]:04X}, {row[1]}, {row[2]}, {row[3]})")
                else:
                    cells.append("(" + ", ".join(str(n) for n in row) + ")")
            out.append("    " + ", ".join(cells) + ",")
        out.append("];")
        out.append("")
    missing = set(TABLES) - seen
    assert not missing, missing
    Path(sys.argv[2]).write_text("\n".join(out))


if __name__ == "__main__":
    main()
